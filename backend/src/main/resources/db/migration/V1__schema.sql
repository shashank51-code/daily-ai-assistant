-- Core schema for the Daily AI Updates & Learning Assistant.
-- All timestamps are stored with time zone (UTC in the database).

create table users (
    id         bigint generated by default as identity primary key,
    name       varchar(120) not null,
    email      varchar(200) not null,
    created_at timestamp with time zone not null default now(),
    constraint uk_users_email unique (email)
);

create table categories (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null,
    slug        varchar(120) not null,
    description varchar(400),
    constraint uk_categories_slug unique (slug)
);

create table articles (
    id           bigint generated by default as identity primary key,
    title        varchar(500) not null,
    url          varchar(1000) not null,
    description  text,
    source       varchar(200),
    published_at timestamp with time zone,
    fetched_at   timestamp with time zone not null default now(),
    image_url    varchar(1000),
    category_id  bigint references categories (id) on delete set null,
    constraint uk_articles_url unique (url)
);

create index idx_articles_published_at on articles (published_at desc);
create index idx_articles_fetched_at on articles (fetched_at desc);
create index idx_articles_category on articles (category_id);

create table article_explanations (
    id                   bigint generated by default as identity primary key,
    article_id           bigint not null references articles (id) on delete cascade,
    what_happened        text,
    technology           text,
    importance           text,
    how_it_works         text,
    where_used           text,
    fresher_learning     text,
    practical_example    text,
    related_technologies text,
    generated_by         varchar(20) not null default 'BASIC',
    generated_at         timestamp with time zone not null default now(),
    constraint uk_explanations_article unique (article_id)
);

create table bookmarks (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    item_type  varchar(20) not null,
    item_id    bigint not null,
    created_at timestamp with time zone not null default now(),
    constraint uk_bookmarks_item unique (user_id, item_type, item_id)
);

create index idx_bookmarks_user on bookmarks (user_id);

create table learning_topics (
    id                  bigint generated by default as identity primary key,
    level_number        integer not null,
    level_name          varchar(120) not null,
    title               varchar(200) not null,
    slug                varchar(200) not null,
    explanation         text,
    prerequisites       text,
    resources           text,
    exercises           text,
    project_ideas       text,
    interview_questions text,
    order_index         integer not null,
    constraint uk_topics_slug unique (slug)
);

create index idx_topics_level on learning_topics (level_number, order_index);

create table learning_progress (
    id           bigint generated by default as identity primary key,
    user_id      bigint not null references users (id) on delete cascade,
    topic_id     bigint not null references learning_topics (id) on delete cascade,
    status       varchar(20) not null default 'NOT_STARTED',
    completed_at timestamp with time zone,
    updated_at   timestamp with time zone not null default now(),
    constraint uk_progress_user_topic unique (user_id, topic_id)
);

create index idx_progress_user on learning_progress (user_id);

create table ai_resources (
    id                  bigint generated by default as identity primary key,
    name                varchar(200) not null,
    category            varchar(120) not null,
    description         text,
    features            text,
    website             varchar(500),
    pricing             text,
    free_alternatives   text,
    trending            boolean not null default false,
    pricing_verified_on varchar(20),
    constraint uk_resources_name unique (name)
);

create table reading_history (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    article_id bigint not null references articles (id) on delete cascade,
    read_at    timestamp with time zone not null default now(),
    constraint uk_history_user_article unique (user_id, article_id)
);

create index idx_history_user_read on reading_history (user_id, read_at desc);

create table daily_tasks (
    id                bigint generated by default as identity primary key,
    day_number        integer not null,
    title             varchar(250) not null,
    description       text,
    kind              varchar(20) not null,
    estimated_minutes integer not null,
    order_index       integer not null
);

create index idx_daily_tasks_day on daily_tasks (day_number, order_index);

create table daily_task_progress (
    id           bigint generated by default as identity primary key,
    user_id      bigint not null references users (id) on delete cascade,
    task_id      bigint not null references daily_tasks (id) on delete cascade,
    completed_at timestamp with time zone not null default now(),
    constraint uk_daily_task_progress unique (user_id, task_id)
);

create index idx_daily_task_progress_user on daily_task_progress (user_id, completed_at desc);
