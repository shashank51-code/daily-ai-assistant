-- Additive history table for scheduled and manually triggered RSS refreshes.
-- Existing tables, records, and prior migrations are not modified.

create table rss_refresh_runs (
    id                bigint generated by default as identity primary key,
    started_at        timestamp with time zone not null,
    finished_at       timestamp with time zone,
    status            varchar(20) not null,
    trigger_source    varchar(40) not null,
    feeds_attempted   integer not null default 0,
    feeds_succeeded   integer not null default 0,
    feeds_failed      integer not null default 0,
    items_read        integer not null default 0,
    saved             integer not null default 0,
    duplicates        integer not null default 0,
    skipped_invalid   integer not null default 0,
    duration_ms       bigint,
    error_summary     text
);

-- Only one execution may be RUNNING at a time. This is the authoritative lock
-- across JVM instances and process restarts.
create unique index uk_rss_refresh_runs_one_running
    on rss_refresh_runs (status)
    where status = 'RUNNING';

create index idx_rss_refresh_runs_started_at on rss_refresh_runs (started_at desc);