# ---------------------------------------------------------------------------
# Structure: SQL only in the tested module, both files parse, module pure.
# ---------------------------------------------------------------------------
Write-Group 'Static structure and parse checks'

$parseErrors = $null
$tokens = $null
$scriptAst = [System.Management.Automation.Language.Parser]::ParseFile($scriptPath, [ref]$tokens, [ref]$parseErrors)
$scriptErrorDetail = ''
if ($parseErrors.Count -gt 0) { $scriptErrorDetail = ' -> ' + ($parseErrors[0].Message) }
Assert-True ($parseErrors.Count -eq 0) ('Invoke-NeonTargetValidation.ps1 parses without errors' + $scriptErrorDetail)

$parseErrors = $null
$tokens = $null
$sqlAst = [System.Management.Automation.Language.Parser]::ParseFile($sqlPath, [ref]$tokens, [ref]$parseErrors)
$sqlErrorDetail = ''
if ($parseErrors.Count -gt 0) { $sqlErrorDetail = ' -> ' + ($parseErrors[0].Message) }
Assert-True ($parseErrors.Count -eq 0) ('NeonValidationSql.ps1 parses without errors' + $sqlErrorDetail)

$commandAsts = $scriptAst.FindAll({ param($n) $n -is [System.Management.Automation.Language.CommandAst] }, $true)
$inlineSql = New-Object System.Collections.Generic.List[string]
$sqlArgs = 0
foreach ($cmd in $commandAsts) {
    $name = $cmd.GetCommandName()
    if ($name -ne 'Invoke-Sql' -and $name -ne 'Invoke-SqlScalar') { continue }
    $elements = $cmd.CommandElements
    for ($i = 0; $i -lt ($elements.Count - 1); $i++) {
        if ($elements[$i] -is [System.Management.Automation.Language.CommandParameterAst] -and $elements[$i].ParameterName -eq 'Sql') {
            $sqlArgs++
            $argText = $elements[$i + 1].Extent.Text
            $isModuleCall = $argText -match '^\(\s*Get-NeonSql[A-Za-z0-9_]+\s*\)$'
            $isVariable   = $argText -match '^\$[A-Za-z_][A-Za-z0-9_]*$'
            if (-not ($isModuleCall -or $isVariable)) { $inlineSql.Add($argText) }
        }
    }
}
Assert-True ($sqlArgs -ge 10) "found the expected Invoke-Sql call sites (found $sqlArgs)"
$inlineDetail = ''
if ($inlineSql.Count -gt 0) { $inlineDetail = ' -> ' + ($inlineSql -join ' ; ') }
Assert-True ($inlineSql.Count -eq 0) ('no inline SQL literals remain in the workflow script' + $inlineDetail)
# Catalog names may still appear in comments/log labels; what must not appear is a statement.
Assert-True (-not ($workflow -match '(?im)^\s*select\b')) 'no SELECT statement text remains in the workflow script (SQL lives in the tested module)'

$topLevel = @($sqlAst.EndBlock.Statements | Where-Object { $_ -isnot [System.Management.Automation.Language.FunctionDefinitionAst] })
$topLevelDetail = ''
if ($topLevel.Count -gt 0) { $topLevelDetail = ' -> ' + ($topLevel[0].Extent.Text) }
Assert-True ($topLevel.Count -eq 0) ('SQL module has no top-level side effects, only function definitions' + $topLevelDetail)

$workflowFunctions = @($scriptAst.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $true) | ForEach-Object { $_.Name })
foreach ($required in @('Assert-ExpectedTarget', 'Assert-TargetGuard', 'Invoke-Sql', 'Test-TargetEmpty', 'Assert-BackupVerified', 'Assert-NoSecretInLog', 'Test-ClientTls')) {
    Assert-True ($workflowFunctions -contains $required) "workflow still defines $required"
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
Write-Host ''
Write-Host ('=' * 72)
Write-Host ("Result: {0} passed, {1} failed, {2} assertions" -f $script:Passed, $script:Failed, ($script:Passed + $script:Failed))
if ($script:Failed -gt 0) {
    Write-Host 'Failed assertions:'
    foreach ($f in $script:Failures) { Write-Host ('  - ' + $f) }
    exit 1
}
Write-Host 'All offline SQL tests passed. No database connection was made.'
exit 0
